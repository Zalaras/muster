// TestMergeSettings_ForeignCommandHookOnSessionStartSurvives covers REQ-3/D6 (D5 guard
// per the plan's own text): a foreign type:"command" SessionStart hook (some other
// tool's own instrumentation, not Muster's) must survive the merge alongside Muster's
// own quoted entry, and a re-merge must not duplicate the foreign one.
func TestMergeSettings_ForeignCommandHookOnSessionStartSurvives(t *testing.T) {
	existing := []byte(`{
		"hooks": {
			"SessionStart": [{"hooks": [{"type": "command", "command": "/Users/x/bin/my-other-tool.sh", "timeout": 10}]}]
		}
	}`)
	cfg := testSettingsConfig()

	out, err := MergeSettings(existing, cfg)
	require.NoError(t, err)

	var doc map[string]json.RawMessage
	require.NoError(t, json.Unmarshal(out, &doc))
	var hooks map[string][]hookGroup
	require.NoError(t, json.Unmarshal(doc["hooks"], &hooks))

	require.Contains(t, hooks, "SessionStart")
	var allCommands []string
	for _, group := range hooks["SessionStart"] {
		for _, entry := range group.Hooks {
			if entry.Command != "" {
				allCommands = append(allCommands, entry.Command)
			}
		}
	}
	assert.Contains(t, allCommands, "/Users/x/bin/my-other-tool.sh", "the foreign SessionStart command hook must survive the merge")
	assert.Contains(t, allCommands, shellQuote(cfg.HookCommand), "Muster's own quoted SessionStart entry must also be present")

	second, err := MergeSettings(out, cfg)
	require.NoError(t, err)
	assert.Equal(t, string(out), string(second), "re-merging must be a true no-op on disk")

	var doc2 map[string]json.RawMessage
	require.NoError(t, json.Unmarshal(second, &doc2))
	var hooks2 map[string][]hookGroup
	require.NoError(t, json.Unmarshal(doc2["hooks"], &hooks2))
	count := 0
	for _, group := range hooks2["SessionStart"] {
		for _, entry := range group.Hooks {
			if entry.Command == "/Users/x/bin/my-other-tool.sh" {
				count++
			}
		}
	}
	assert.Equal(t, 1, count, "the foreign entry must not be duplicated across repeated merges")
}

// TestWriteWrapperScripts covers D9/REQ-5/REQ-6/REQ-7/REQ-15: the generated command-hook
// wrapper script paths, executable mode, a 2s curl timeout (never 5, CLAUDE.md hard
// rule), always exit 0, and the envelope fields built from the pane environment — one
// hook.sh script now serves all eleven events.
func TestWriteWrapperScripts(t *testing.T) {
	dir := t.TempDir()

	hookScript, statusLinePath, legacyScript, err := WriteWrapperScripts(dir, "http://127.0.0.1:8765", "tok123")
	require.NoError(t, err)

	assert.Equal(t, filepath.Join(dir, "hook.sh"), hookScript)
	assert.Equal(t, filepath.Join(dir, "status-line.sh"), statusLinePath)
	assert.Equal(t, filepath.Join(dir, "hook-sessionstart.sh"), legacyScript)

	for _, path := range []string{hookScript, statusLinePath} {
		info, statErr := os.Stat(path)
		require.NoError(t, statErr)
		// 0o700, not 0o755 (review Major 9): the script embeds the ingest token in
		// cleartext, and only the daemon's own user ever needs to execute it.
		assert.Equal(t, os.FileMode(0o700), info.Mode().Perm())
	}

	hookBytes, err := os.ReadFile(hookScript)
	require.NoError(t, err)
	hookText := string(hookBytes)
	assert.Contains(t, hookText, "http://127.0.0.1:8765/ingest/tok123/hook")
	assert.Contains(t, hookText, "--max-time 2")
	assert.Contains(t, hookText, "exit 0")
	assert.Contains(t, hookText, "MUSTER_SESSION")
	assert.Contains(t, hookText, "TMUX_PANE")
	assert.NotContains(t, hookText, "--max-time 5")

	statusLineScript, err := os.ReadFile(statusLinePath)
	require.NoError(t, err)
	assert.Contains(t, string(statusLineScript), "http://127.0.0.1:8765/ingest/tok123/status")
}

