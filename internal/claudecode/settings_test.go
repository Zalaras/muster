// TestMergeSettings_FreshFileRegistersCommandEntryOnAllElevenEvents covers D1/REQ-1: a
// fresh file gets a type:"command" entry on every one of the eleven events
// (httpHookEvents + SessionStart), each pointing at the single-quoted hook script path
// with the 2s timeout — and D5: it must never gain an allowedHttpHookUrls key.
func TestMergeSettings_FreshFileRegistersCommandEntryOnAllElevenEvents(t *testing.T) {
	require.Len(t, allHookEvents, 11, "sanity: REQ-1 names eleven events")
	cfg := testSettingsConfig()

	out, err := MergeSettings(nil, cfg)
	require.NoError(t, err)

	var doc map[string]json.RawMessage
	require.NoError(t, json.Unmarshal(out, &doc))
	var hooks map[string][]hookGroup
	require.NoError(t, json.Unmarshal(doc["hooks"], &hooks))

	for _, event := range allHookEvents {
		require.Contains(t, hooks, event)
		require.Len(t, hooks[event], 1, "event %s", event)
		require.Len(t, hooks[event][0].Hooks, 1, "event %s", event)
		entry := hooks[event][0].Hooks[0]
		assert.Equal(t, "command", entry.Type, "event %s", event)
		assert.Equal(t, shellQuote(cfg.HookCommand), entry.Command, "event %s", event)
		assert.Equal(t, hookTimeoutSeconds, entry.Timeout, "event %s", event)
		assert.LessOrEqual(t, entry.Timeout, 2, "CLAUDE.md hard rule: hook timeouts are 1-2s, never 5")
	}

	var statusLine hookEntry
	require.NoError(t, json.Unmarshal(doc["statusLine"], &statusLine))
	assert.Equal(t, "command", statusLine.Type)
	assert.Equal(t, shellQuote(cfg.StatusLineCommand), statusLine.Command)
	assert.Zero(t, statusLine.Timeout, "statusLine carries no timeout")

	_, hasAllowed := doc["allowedHttpHookUrls"]
	assert.False(t, hasAllowed, "D5: a fresh file must never gain an allowedHttpHookUrls key")
}

