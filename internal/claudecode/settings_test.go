// TestMergeSettings_MigrationFixture_ExactlyOneMusterEntryPerEventNoLegacySurvives
// covers D2/D3/Edge Case 1 — the scenario the plan calls "most likely to be got wrong":
// every existing user directory has ten http entries and a legacy SessionStart command
// entry (both a bare and a quoted form observed in the wild across daemon versions).
// After the merge: eleven command entries (one each), no http entries anywhere, and
// neither legacy form of hook-sessionstart.sh survives.
func TestMergeSettings_MigrationFixture_ExactlyOneMusterEntryPerEventNoLegacySurvives(t *testing.T) {
	cfg := testSettingsConfig()

	out, err := MergeSettings(migrationFixture(), cfg)
	require.NoError(t, err)

	var doc map[string]json.RawMessage
	require.NoError(t, json.Unmarshal(out, &doc))
	var hooks map[string][]hookGroup
	require.NoError(t, json.Unmarshal(doc["hooks"], &hooks))

	for _, event := range httpHookEvents {
		var musterCount int
		for _, group := range hooks[event] {
			for _, entry := range group.Hooks {
				// PostToolUse deliberately carries one foreign http entry (a remote
				// host) that must survive (D6/Edge Case 2) — only Muster's own
				// ingest-shaped http entry may never survive the migration (D2).
				if entry.Type == "http" {
					assert.False(t, isMusterIngestURL(entry.URL), "event %s: Muster's own http entry must not survive the migration (found url=%q)", event, entry.URL)
				}
				if entry.Type == "command" && entry.Command == shellQuote(cfg.HookCommand) {
					musterCount++
				}
			}
		}
		assert.Equal(t, 1, musterCount, "event %s: exactly one Muster command entry, no duplicates", event)
	}

	var sessionStartCommands []string
	for _, group := range hooks["SessionStart"] {
		for _, entry := range group.Hooks {
			assert.NotEqual(t, "http", entry.Type, "SessionStart must never carry an http entry")
			sessionStartCommands = append(sessionStartCommands, entry.Command)
		}
	}
	assert.Contains(t, sessionStartCommands, shellQuote(cfg.HookCommand), "Muster's own quoted entry must be present")
	assert.Contains(t, sessionStartCommands, "/Users/x/bin/my-other-tool.sh", "the foreign SessionStart command hook must survive")
	assert.NotContains(t, sessionStartCommands, "/data/hook-sessionstart.sh", "the bare legacy entry must not survive")
	assert.NotContains(t, sessionStartCommands, "'/data/hook-sessionstart.sh'", "the quoted legacy entry must not survive")
	assert.Len(t, sessionStartCommands, 2, "exactly Muster's own entry plus the one foreign entry — both legacy entries must be gone")

	assert.NotContains(t, string(out), "hook-sessionstart.sh", "belt-and-braces: the legacy filename must not appear anywhere in the output")
}

